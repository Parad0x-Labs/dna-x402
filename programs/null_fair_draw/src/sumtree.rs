/// A `(hash, weight)` pair.
pub type Pair = ([u8; 32], u64);

/// Leaf commitment of one entry.
pub fn leaf(draw: &[u8; 32], wallet: &[u8; 32], weight: u64) -> [u8; 32] {
    hashv(&[LEAF_TAG, draw, wallet, &weight.to_le_bytes()]).to_bytes()
}

/// Inner node hash.
pub fn node_hash(l: &Pair, r: &Pair) -> [u8; 32] {
    hashv(&[NODE_PREFIX, &l.0, &l.1.to_le_bytes(), &r.0, &r.1.to_le_bytes()]).to_bytes()
}

/// Inner node `(hash, weight)`; `None` if the weights overflow.
pub fn node(l: &Pair, r: &Pair) -> Option<Pair> {
    Some((node_hash(l, r), l.1.checked_add(r.1)?))
}

/// Recompute the zero-subtree table.
pub fn compute_zeros() -> [[u8; 32]; MAX_LIST_DEPTH + 1] {
    let mut z = [[0u8; 32]; MAX_LIST_DEPTH + 1];
    for i in 0..MAX_LIST_DEPTH {
        z[i + 1] = node_hash(&(z[i], 0), &(z[i], 0));
    }
    z
}

fn read_pair(b: &[u8]) -> Pair {
    let mut h = [0u8; 32];
    h.copy_from_slice(&b[..32]);
    let mut w = [0u8; 8];
    w.copy_from_slice(&b[32..40]);
    (h, u64::from_le_bytes(w))
}

fn write_pair(b: &mut [u8], p: &Pair) {
    b[..32].copy_from_slice(&p.0);
    b[32..40].copy_from_slice(&p.1.to_le_bytes());
}

/// Append leaf `(hash, weight)` at position `index` of a depth-[`OPEN_DEPTH`]
/// tree whose frontier is `filled` ([`FRONTIER_LEN`] bytes, entry `l` is the
/// last left node written at level `l`). Returns the new root pair.
pub fn append(filled: &mut [u8], index: u64, leaf: &Pair) -> Option<Pair> {
    let mut cur = *leaf;
    let mut idx = index;
    for (level, zero) in ZEROS.iter().take(OPEN_DEPTH).enumerate() {
        let slot = &mut filled[level * PAIR_LEN..(level + 1) * PAIR_LEN];
        if idx & 1 == 0 {
            write_pair(slot, &cur);
            cur = node(&cur, &(*zero, 0))?;
        } else {
            let left = read_pair(slot);
            cur = node(&left, &cur)?;
        }
        idx >>= 1;
    }
    Some(cur)
}

/// Verify that leaf `(leaf_hash, weight)` sits at `index` under the root
/// `(root, total)` of a depth-`depth` tree with `count` entries, given the
/// sibling pairs `path` (`depth * PAIR_LEN` bytes). Returns the leaf's
/// interval start (its prefix sum), or `None` if anything does not match.
pub fn verify(
    root: &[u8; 32],
    total: u64,
    depth: usize,
    count: u64,
    index: u64,
    leaf_hash: &[u8; 32],
    weight: u64,
    path: &[u8],
) -> Option<u64> {
    if weight == 0 || index >= count || path.len() != depth * PAIR_LEN || depth > MAX_LIST_DEPTH {
        return None;
    }
    if depth < 64 && (index >> depth) != 0 {
        return None;
    }
    let mut acc: Pair = (*leaf_hash, weight);
    let mut prefix: u64 = 0;
    for level in 0..depth {
        let sib = read_pair(&path[level * PAIR_LEN..(level + 1) * PAIR_LEN]);
        if (index >> level) & 1 == 1 {
            prefix = prefix.checked_add(sib.1)?;
            acc = node(&sib, &acc)?;
        } else {
            acc = node(&acc, &sib)?;
        }
    }
    if acc.0 != *root || acc.1 != total {
        return None;
    }
    Some(prefix)
}

/// Off-chain helper: all levels of a depth-`depth` tree over `leaves`
/// (`levels[0]` is the padded leaf level, `levels[depth]` the root).
pub fn build(leaves: &[Pair], depth: usize) -> Vec<Vec<Pair>> {
    let mut levels = Vec::with_capacity(depth + 1);
    let mut cur: Vec<Pair> = leaves.to_vec();
    for z in ZEROS.iter().take(depth) {
        if cur.len() % 2 == 1 {
            cur.push((*z, 0));
        }
        if cur.is_empty() {
            cur.push((*z, 0));
            cur.push((*z, 0));
        }
        levels.push(cur.clone());
        cur = cur.chunks(2).map(|c| node(&c[0], &c[1]).expect("weight overflow")).collect();
    }
    levels.push(cur);
    levels
}

/// Off-chain helper: root pair of a depth-`depth` tree over `leaves`.
pub fn root_of(leaves: &[Pair], depth: usize) -> Pair {
    if leaves.is_empty() {
        return (ZEROS[depth], 0);
    }
    build(leaves, depth)[depth][0]
}

/// Off-chain helper: proof bytes of leaf `index`.
pub fn proof_of(leaves: &[Pair], depth: usize, index: usize) -> Vec<u8> {
    let levels = build(leaves, depth);
    let mut out = vec![0u8; depth * PAIR_LEN];
    let mut i = index;
    for l in 0..depth {
        let sib = levels[l].get(i ^ 1).copied().unwrap_or((ZEROS[l], 0));
        write_pair(&mut out[l * PAIR_LEN..(l + 1) * PAIR_LEN], &sib);
        i >>= 1;
    }
    out
}

/// Smallest depth (at least 1) whose tree holds `count` leaves.
pub fn depth_for(count: u64) -> usize {
    let mut d = 1usize;
    while (1u64 << d) < count {
        d += 1;
    }
    d
}

#[cfg(test)]
mod tests {
    use super::*;

    fn lf(i: u64, w: u64) -> Pair {
        (leaf(&[7u8; 32], &[i as u8; 32], w), w)
    }

    #[test]
    fn zero_table_matches() {
        assert_eq!(compute_zeros(), ZEROS);
        assert_eq!(root_of(&[], OPEN_DEPTH), (ZEROS[OPEN_DEPTH], 0));
    }

    #[test]
    fn append_matches_batch_and_proofs_give_prefix_sums() {
        let mut filled = [0u8; FRONTIER_LEN];
        let mut leaves = Vec::new();
        let mut total = 0u64;
        for i in 0..37u64 {
            let l = lf(i, 1 + (i * 7) % 5);
            leaves.push(l);
            total += l.1;
            let r = append(&mut filled, i, &l).unwrap();
            assert_eq!(r, root_of(&leaves, OPEN_DEPTH), "root after {} leaves", i + 1);
            assert_eq!(r.1, total);
        }
        let (root, total) = root_of(&leaves, OPEN_DEPTH);
        let mut prefix = 0u64;
        for (i, l) in leaves.iter().enumerate() {
            let p = proof_of(&leaves, OPEN_DEPTH, i);
            let n = leaves.len() as u64;
            assert_eq!(verify(&root, total, OPEN_DEPTH, n, i as u64, &l.0, l.1, &p), Some(prefix));
            // Wrong index, weight, count or total fails.
            assert_eq!(verify(&root, total, OPEN_DEPTH, n, (i as u64) ^ 1, &l.0, l.1, &p), None);
            assert_eq!(verify(&root, total, OPEN_DEPTH, n, i as u64, &l.0, l.1 + 1, &p), None);
            assert_eq!(verify(&root, total, OPEN_DEPTH, i as u64, i as u64, &l.0, l.1, &p), None);
            assert_eq!(verify(&root, total + 1, OPEN_DEPTH, n, i as u64, &l.0, l.1, &p), None);
            prefix += l.1;
        }
    }

    #[test]
    fn small_depth_lists_and_edges() {
        for n in [1usize, 2, 3, 4, 5, 8, 9] {
            let d = depth_for(n as u64);
            let leaves: Vec<Pair> = (0..n as u64).map(|i| lf(i, 10 + i)).collect();
            let (root, total) = root_of(&leaves, d);
            for i in [0, n - 1] {
                let p = proof_of(&leaves, d, i);
                let start: u64 = leaves[..i].iter().map(|l| l.1).sum();
                assert_eq!(verify(&root, total, d, n as u64, i as u64, &leaves[i].0, leaves[i].1, &p), Some(start));
            }
        }
        assert_eq!(depth_for(1), 1);
        assert_eq!(depth_for(2), 1);
        assert_eq!(depth_for(3), 2);
        assert_eq!(depth_for(1 << 22), 22);
    }

    #[test]
    fn zero_weight_leaf_never_verifies() {
        let leaves = vec![lf(0, 3), lf(1, 0), lf(2, 4)];
        let (root, total) = root_of(&leaves, 2);
        let p = proof_of(&leaves, 2, 1);
        assert_eq!(verify(&root, total, 2, 3, 1, &leaves[1].0, 0, &p), None);
    }
}
