//! SHA-256 sum tree of entries: every node commits to its hash and to the
//! total weight below it, so a proof authenticates the prefix sum of a leaf.
//!
//! ```text
//! leaf   = SHA-256("null-fair-draw:leaf:v1" || draw[32] || wallet[32] || weight_le[8])
//! node   = SHA-256(0x01 || left_hash[32] || left_weight_le[8] || right_hash[32] || right_weight_le[8])
//! weight(node) = left_weight + right_weight
//! ```
//!
//! Empty positions are `(32 zero bytes, weight 0)`; `ZEROS[i]` is the empty
//! subtree of height `i`. A tree of depth `d` holds `2^d` positions, of which
//! the leading `leaf_count` are entries. The root commitment is
//! `(root_hash, total_weight)`.
//!
//! Leaf `i` owns the half-open interval `[start_i, start_i + weight_i)` of
//! `[0, total)`, where `start_i` is the sum of the weights of the leaves left of
//! it. A proof is the `d` sibling pairs `(hash, weight)` from the leaf up; bit
//! `l` of the index says whether the node at level `l` is a right child, and
//! then the left sibling's weight is added to the prefix. Because every
//! weight is inside a hash, a proof that reaches the committed root and total
//! fixes `start_i` and `weight_i`: the intervals of distinct leaves are disjoint
//! and cover `[0, total)`, so every point lies in exactly one leaf with
//! non-zero weight, and a zero-weight leaf contains no point.
//!
//! A leaf preimage is 94 bytes and starts with the 22-byte tag; a node
//! preimage is 81 bytes and starts with 0x01, so neither can be read as the
//! other.

use solana_program::hash::hashv;

/// Domain separation tag of a leaf.
