//! Per-round incremental SHA-256 Merkle tree of tickets.
//!
//! ```text
//! leaf = SHA-256("null-lottery-pools:ticket:v1" || pool[32] || round_id_le[8]
//!                || owner[32] || numbers[8] || ticket_index_le[8])
//! node = SHA-256(0x01 || left[32] || right[32])
//! ```
//!
//! `numbers` are the ticket's `k` numbers in ascending order, zero padded to 8
//! bytes. The tree has fixed depth [`TREE_DEPTH`] (2^20 tickets per round); an
//! empty leaf is 32 zero bytes and `ZEROS[i]` is the root of an empty subtree of
//! height `i`. BuyTicket appends leaf `ticket_index = ticket_count` with the
//! frontier ("filled subtrees") method: [`TREE_DEPTH`] node hashes per append, and
//! the frontier entry read at level `i` is always one written earlier in the same
//! round. A proof is the [`TREE_DEPTH`] sibling hashes from the leaf up; bit `i` of
//! the ticket index says whether the node at level `i` is a right child.
//!
//! Hash choice: `sol_sha256` costs 85 CU base plus 1 CU per 2 bytes of input
//! (minimum 10 CU per slice), about 127 CU for a 65-byte node, while
//! `sol_poseidon` on BN254 with 2 inputs costs 61 * 2^2 + 542 = 786 CU and needs
//! every input reduced below the field modulus first (a raw public key often is
//! not). A 20-level append is about 2.5k CU with SHA-256 and about 16k CU with
//! Poseidon, so the tree uses SHA-256. A leaf starts with the 28-byte tag and is
//! 116 bytes long; a node preimage is 65 bytes and starts with 0x01, so a leaf
//! preimage can never be read as a node preimage.

use solana_program::hash::hashv;

/// Domain separation tag of a ticket leaf.
pub const TICKET_LEAF_TAG: &[u8] = b"null-lottery-pools:ticket:v1";
/// Prefix of an inner node preimage.
pub const NODE_PREFIX: &[u8] = &[0x01];
/// Tree depth (levels of nodes above the leaves).
pub const TREE_DEPTH: usize = 20;
/// Ticket capacity of one round.
pub const MAX_TICKETS: u64 = 1 << TREE_DEPTH;
/// Bytes of the frontier stored in the pool account.
pub const FRONTIER_LEN: usize = TREE_DEPTH * 32;

