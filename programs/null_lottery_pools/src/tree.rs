/// Leaf commitment of one ticket.
pub fn ticket_leaf(
    pool: &[u8; 32],
    round_id: u64,
    owner: &[u8; 32],
    numbers: &[u8; 8],
    ticket_index: u64,
) -> [u8; 32] {
    hashv(&[
        TICKET_LEAF_TAG,
        pool,
        &round_id.to_le_bytes(),
        owner,
        numbers,
        &ticket_index.to_le_bytes(),
    ])
    .to_bytes()
}

/// Inner node.
pub fn node(left: &[u8; 32], right: &[u8; 32]) -> [u8; 32] {
    hashv(&[NODE_PREFIX, left, right]).to_bytes()
}

/// Append `leaf` at position `index` to the frontier `filled`
/// ([`FRONTIER_LEN`] bytes) and return the new root.
pub fn append(filled: &mut [u8], index: u64, leaf: &[u8; 32]) -> [u8; 32] {
    debug_assert!(filled.len() >= FRONTIER_LEN);
    let mut cur = *leaf;
    let mut idx = index;
    for (level, zero) in ZEROS.iter().take(TREE_DEPTH).enumerate() {
        let slot = &mut filled[level * 32..level * 32 + 32];
        if idx & 1 == 0 {
            slot.copy_from_slice(&cur);
            cur = node(&cur, zero);
        } else {
            let mut left = [0u8; 32];
            left.copy_from_slice(slot);
            cur = node(&left, &cur);
        }
        idx >>= 1;
    }
    cur
}

/// Root reached from `leaf` at `index` with sibling path `proof`.
pub fn root_from_proof(leaf: &[u8; 32], index: u64, proof: &[[u8; 32]; TREE_DEPTH]) -> [u8; 32] {
    let mut acc = *leaf;
    for (level, sibling) in proof.iter().enumerate() {
        acc = if (index >> level) & 1 == 1 { node(sibling, &acc) } else { node(&acc, sibling) };
    }
    acc
}

/// Recompute the zero-subtree table.
pub fn compute_zeros() -> [[u8; 32]; TREE_DEPTH + 1] {
    let mut z = [[0u8; 32]; TREE_DEPTH + 1];
    for i in 0..TREE_DEPTH {
        z[i + 1] = node(&z[i], &z[i]);
    }
    z
}

/// Off-chain helper: root of a round with the given leaves (in ticket order).
pub fn root_of(leaves: &[[u8; 32]]) -> [u8; 32] {
    let mut level: Vec<[u8; 32]> = leaves.to_vec();
    for z in ZEROS.iter().take(TREE_DEPTH) {
        if level.is_empty() {
            level.push(*z);
        }
        level = level
            .chunks(2)
            .map(|c| node(&c[0], c.get(1).unwrap_or(z)))
            .collect();
    }
    level[0]
}

/// Off-chain helper: sibling path of leaf `index`.
pub fn proof_of(leaves: &[[u8; 32]], index: usize) -> [[u8; 32]; TREE_DEPTH] {
    let mut proof = [[0u8; 32]; TREE_DEPTH];
    let mut level: Vec<[u8; 32]> = leaves.to_vec();
    let mut i = index;
    for (lvl, z) in ZEROS.iter().take(TREE_DEPTH).enumerate() {
        proof[lvl] = *level.get(i ^ 1).unwrap_or(z);
        level = level
            .chunks(2)
            .map(|c| node(&c[0], c.get(1).unwrap_or(z)))
            .collect();
        i >>= 1;
    }
    proof
}

#[cfg(test)]
mod tests {
    use super::*;

    fn leaf(i: u64) -> [u8; 32] {
        ticket_leaf(&[7u8; 32], 3, &[9u8; 32], &[1, 2, 3, 0, 0, 0, 0, 0], i)
    }

    #[test]
    fn zero_table_matches() {
        assert_eq!(compute_zeros(), ZEROS);
        assert_eq!(root_of(&[]), ZEROS[TREE_DEPTH]);
    }

    #[test]
    fn incremental_matches_batch_and_proofs_verify() {
        let mut filled = [0u8; FRONTIER_LEN];
        let mut leaves = Vec::new();
        for i in 0..37u64 {
            let l = leaf(i);
            leaves.push(l);
            let r = append(&mut filled, i, &l);
            assert_eq!(r, root_of(&leaves), "root after {} leaves", i + 1);
        }
        let root = root_of(&leaves);
        for (i, l) in leaves.iter().enumerate() {
            let p = proof_of(&leaves, i);
            assert_eq!(root_from_proof(l, i as u64, &p), root);
            // Wrong index fails.
            assert_ne!(root_from_proof(l, (i as u64) ^ 1, &p), root);
        }
    }

    #[test]
    fn leaf_binds_every_field() {
        let base = ticket_leaf(&[1; 32], 2, &[3; 32], &[4, 5, 0, 0, 0, 0, 0, 0], 6);
        assert_ne!(base, ticket_leaf(&[0; 32], 2, &[3; 32], &[4, 5, 0, 0, 0, 0, 0, 0], 6));
        assert_ne!(base, ticket_leaf(&[1; 32], 1, &[3; 32], &[4, 5, 0, 0, 0, 0, 0, 0], 6));
        assert_ne!(base, ticket_leaf(&[1; 32], 2, &[0; 32], &[4, 5, 0, 0, 0, 0, 0, 0], 6));
        assert_ne!(base, ticket_leaf(&[1; 32], 2, &[3; 32], &[4, 6, 0, 0, 0, 0, 0, 0], 6));
        assert_ne!(base, ticket_leaf(&[1; 32], 2, &[3; 32], &[4, 5, 0, 0, 0, 0, 0, 0], 7));
    }
}
