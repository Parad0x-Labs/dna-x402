// Inline src/core.ts (TypeScript types stripped, exports dropped) into
// verify.html between the BEGIN/END markers. The SDK test fails if the page
// and the core drift apart.
import { readFileSync, writeFileSync } from "node:fs";
import { stripTypeScriptTypes } from "node:module";

const BEGIN = "// BEGIN core.ts (generated by scripts/build-verify-page.mjs)";
const END = "// END core.ts";

export function coreJs() {
  const src = readFileSync(new URL("../src/core.ts", import.meta.url), "utf8");
  return stripTypeScriptTypes(src, { mode: "strip" })
    .replace(/^export /gm, "")
    .split("\n")
    .map((l) => l.replace(/\s+$/, ""))
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

export function render(html) {
  const a = html.indexOf(BEGIN);
  const b = html.indexOf(END);
  if (a < 0 || b < a) throw new Error("verify.html markers not found");
  return html.slice(0, a + BEGIN.length) + "\n" + coreJs() + "\n" + html.slice(b);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const page = new URL("../verify.html", import.meta.url);
  writeFileSync(page, render(readFileSync(page, "utf8")));
}
